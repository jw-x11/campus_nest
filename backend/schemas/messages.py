from datetime import datetime
from typing import Annotated, Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, StringConstraints

from schemas.users import UserPublicResponse

MAX_MESSAGE_LENGTH = 2000

MessageBody = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=MAX_MESSAGE_LENGTH)]


class ConversationCreateRequest(BaseModel):
    """Open the thread about a space. With booking_id, the parties come from that booking."""
    model_config = ConfigDict(populate_by_name=True, extra="forbid")

    space_id: Annotated[int, Field(ge=1)]
    booking_id: UUID | None = None


class MessageSendRequest(BaseModel):
    model_config = ConfigDict(populate_by_name=True, extra="forbid")

    body: MessageBody
    # Generated by the client per message; resending with the same id returns the original message.
    client_msg_id: UUID


class MessageResponse(BaseModel):
    model_config = ConfigDict(populate_by_name=True, from_attributes=True, extra="ignore")

    id: UUID
    conversation_id: UUID
    sender_id: UUID
    body: str
    client_msg_id: UUID
    created_at: datetime


class ConversationResponse(BaseModel):
    model_config = ConfigDict(populate_by_name=True, extra="forbid")

    id: UUID
    space_id: int
    booking_id: UUID | None
    renter_id: UUID
    owner_id: UUID
    # The caller's side of the conversation.
    role: Literal["renter", "owner"]
    other_user: UserPublicResponse | None
    last_message: MessageResponse | None
    last_message_at: datetime | None
    unread_count: int
    created_at: datetime


class ConversationResponseList(BaseModel):
    model_config = ConfigDict(populate_by_name=True, extra="forbid")

    conversations: list[ConversationResponse]
    total_count: int
    page: Annotated[int, Field(ge=1)]
    page_size: Annotated[int, Field(ge=1)]


class MessagePage(BaseModel):
    """Messages oldest first. has_more says whether another page exists past this one in the requested direction."""
    model_config = ConfigDict(populate_by_name=True, extra="forbid")

    messages: list[MessageResponse]
    has_more: bool


class UnreadResponse(BaseModel):
    model_config = ConfigDict(populate_by_name=True, extra="forbid")

    total: int
    conversations: dict[UUID, int]


class WsTicketResponse(BaseModel):
    model_config = ConfigDict(populate_by_name=True, extra="forbid")

    ticket: str
    expires_in: int


# ---- WebSocket frames the client sends

class WsSend(BaseModel):
    model_config = ConfigDict(extra="forbid")

    type: Literal["send"]
    conversation_id: UUID
    body: MessageBody
    client_msg_id: UUID


class WsTyping(BaseModel):
    model_config = ConfigDict(extra="forbid")

    type: Literal["typing"]
    conversation_id: UUID


class WsPong(BaseModel):
    model_config = ConfigDict(extra="forbid")

    type: Literal["pong"]


class WsInbound(BaseModel):
    frame: Annotated[WsSend | WsTyping | WsPong, Field(discriminator="type")]
